CREATE TABLE IF NOT EXISTS kv (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS leases (name TEXT PRIMARY KEY, owner TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS videos (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, url TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1, episode INTEGER NOT NULL DEFAULT 1,
  first_seen INTEGER NOT NULL, last_seen INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS outbox (
  id TEXT NOT NULL, channel TEXT NOT NULL, payload TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0, next_at INTEGER NOT NULL DEFAULT 0,
  sent_at INTEGER, created_at INTEGER NOT NULL,
  PRIMARY KEY (id, channel)
);
CREATE INDEX IF NOT EXISTS outbox_pending ON outbox(sent_at, next_at);
